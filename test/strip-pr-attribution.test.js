'use strict';
// Pull-request descriptions carry no tool attribution (owner, 2026-10-25).
// The cloud session's GitHub gateway appends a footer to every description
// it writes and again on every edit; the pr-attribution workflow strips it
// on GitHub's side (.github/scripts/strip-pr-attribution.js).
const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');
const { stripAttribution } = require('../.github/scripts/strip-pr-attribution');

const read = (f) => fs.readFileSync(path.join(__dirname, '..', f), 'utf8');
const BODY = 'Follow-up to #3.\n\n## What changes\n\n- The walk keeps its chains.\n\n---\n\n## Tests\n\nThe touched files pass.';

test('the gateway footer goes, rule and all, on its first write and on every edit', () => {
  assert.strictEqual(stripAttribution(`${BODY}\n\n---\n_Generated by [Claude Code](https://claude.ai/code/session_01Mzut2AveArMucyUpH9ZQ4n)_`), BODY);
  assert.strictEqual(stripAttribution(`${BODY}\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_`), BODY);
  assert.strictEqual(stripAttribution(`${BODY}\n\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n`), BODY);
});

test('the tool\'s own lines go too: "Generated with", the session link, the trailers', () => {
  assert.strictEqual(stripAttribution(`${BODY}\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\nhttps://claude.ai/code/session_01Mzut2AveArMucyUpH9ZQ4n`), BODY);
  assert.strictEqual(stripAttribution(`${BODY}\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>\nClaude-Session: https://claude.ai/code/session_01Mzut2AveArMucyUpH9ZQ4n`), BODY);
  assert.strictEqual(stripAttribution('Fix.\n\nco-authored-by: Claude <noreply@anthropic.com>'), 'Fix.');
});

test('everything else is kept as written: a rule between sections, Claude named as a product, a clean body', () => {
  assert.strictEqual(stripAttribution(BODY), BODY, 'unchanged, the same string');
  const product = 'The MCP connector lets Claude and ChatGPT run scans.\n\nClaude Desktop config below.';
  assert.strictEqual(stripAttribution(product), product);
  assert.strictEqual(stripAttribution(''), '');
  assert.strictEqual(stripAttribution(null), null);
  assert.strictEqual(stripAttribution(undefined), undefined);
});

test('the workflow runs main\'s own script on every opened, edited or reopened pull request, and sweeps when it lands', () => {
  const wf = read('.github/workflows/pr-attribution.yml');
  assert.match(wf, /pull_request_target:\n\s+types: \[opened, edited, reopened\]/);
  assert.match(wf, /ref: \$\{\{ github\.event\.repository\.default_branch \}\}/, 'never the pull request\'s own code');
  assert.match(wf, /pull-requests: write/);
  assert.match(wf, /- '\.github\/scripts\/strip-pr-attribution\.js'/);
  assert.match(wf, /PR_NUMBER: \$\{\{ github\.event\.pull_request\.number \}\}/);
});
